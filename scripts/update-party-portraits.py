"""Read original sprite alpha bounds for sidebar presentation; never modify artwork."""
import json
import re
from pathlib import Path
from PIL import Image
root = Path(__file__).resolve().parent.parent
avatars = ['王子','公主','男騎士','女騎士','男法師','女法師','男妖精','女妖精','男黑暗妖精','女黑暗妖精','男龍騎士','女龍騎士','男幻術士','女幻術士','男戰士','女戰士']
paths = [p for avatar in avatars for p in (root/'assets/classanim'/avatar).glob('*_idle_0.png')]
names = set()
for module in ['22-pets.js','23-summons.js','31-castle-guards.js']:
    text = (root/'js'/module).read_text()
    names.update(re.findall(r'(?:n|form)\s*:\s*[\'"]([^\'"]+)[\'"]', text))
    if module == '22-pets.js':
        names.update(re.findall(r'^\s*[\'"]([^\'"]+)[\'"]\s*:\s*\{', text, re.M))
for element in ['水','火','風','地']:
    names.update([element+'屬性精靈','強力'+element+'屬性精靈'])
paths += [root/'assets/anim'/name/'d6/idle_0.png' for name in names]
bounds = {}
for path in sorted(set(paths)):
    if not path.is_file():continue
    with Image.open(path) as image:
        box = image.convert('RGBA').getchannel('A').getbbox()
        if box:bounds[str(path.relative_to(root))] = [image.width,image.height,box[0],box[1],box[2]-box[0],box[3]-box[1]]
(root/'js/party-portrait-bounds.js').write_text('// Original sprite alpha bounds, generated by scripts/update-party-portraits.py.\nconst PARTY_PORTRAIT_BOUNDS = '+json.dumps(bounds,ensure_ascii=False,separators=(',',':'))+';\n')
print(f'Read alpha bounds for {len(bounds)} original sprites; original images unchanged.')
